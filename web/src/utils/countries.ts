const toFlag = (code: string) =>
  String.fromCodePoint(
    ...[...code].map(ch => 0x1f1e6 + ch.charCodeAt(0) - 65),
  );

export const COUNTRIES: readonly Country[] = RAW.map(([code, callingCode, name]) => ({
  code,
  callingCode,
  name,
  flag: toFlag(code),
  dial: `+${callingCode}`,
  label: `${toFlag(code)} +${callingCode} ${code}`,
}));

const BY_CODE = new Map(COUNTRIES.map(c => [c.code, c]));

export function getCountry(code: CountryCode): Country | undefined {
  return BY_CODE.get(code);
}

export function getCallingCode(code: CountryCode): string {
  return BY_CODE.get(code)?.callingCode ?? '';
}

/** Case-insensitive match on name, ISO code or calling code. */
export function searchCountries(query: string): readonly Country[] {
  const q = query.trim().toLowerCase().replace(/^\+/, '');
  if (!q) {
    return COUNTRIES;
  }
  return COUNTRIES.filter(
    c =>
      c.name.toLowerCase().includes(q) ||
      c.code.toLowerCase() === q ||
      c.callingCode.startsWith(q),
  );
}
